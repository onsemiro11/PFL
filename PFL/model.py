"""PFL: attention encoder + rectified-flow decoder.

Ego plan is injected in the encoder (grid merge, plan token, and the relational
feature). Trajectories are generated by integrating v_theta(x_t, t, c) from noise
at t=0 to data at t=1.

The flow does not act on raw future coordinates. It acts on the residual from the
target's own constant-velocity extrapolation, standardised per horizon step and
per axis. On NGSIM the raw future has a lateral std of ~1 ft against a
longitudinal std of ~44 ft, so a single shared scale leaves the lateral channel
with roughly 0.06% of the longitudinal gradient and it is never learned. The
residual parameterisation also shrinks what the vector field has to transport:
the longitudinal target no longer carries a growing mean of up to ~400 ft.
The baseline is longitudinal-only -- see cv_velocity for why extrapolating
the lateral finite difference makes that channel worse.
"""
import torch
import torch.nn as nn
import torch.nn.functional as F

from encoder import PFLEncoder, cv_baseline
from vf import VectorField

# Buffers that are derived rather than learned, and so must not gate a load. loss_w was
# briefly persistent; it is recomputed from loss_mode and res_std, so checkpoints written
# during that window still load cleanly.
DERIVED_BUFFERS = ("loss_w",)


def strip_derived(sd):
    return {k: v for k, v in sd.items() if k not in DERIVED_BUFFERS}


class PFLNet(nn.Module):
    def __init__(self, args):
        super().__init__()
        self.args = args
        self.out_length = args.out_length
        self.encoder = PFLEncoder(args)
        # A second, independent encoder for the regression path. The two objectives were
        # measured to pull the shared encoder in near-orthogonal directions (cosine ~0.1),
        # so neither reweighting nor ordering removes the drift -- only not sharing the
        # parameters does. Both are seeded from the same weights at init_from time, so the
        # benefit of a regression-pretrained representation is kept and only the ongoing
        # coupling is cut.
        self.use_mean_head = bool(getattr(args, "use_mean_head", False)
                                  or getattr(args, "mean_weight", 0.0)
                                  or getattr(args, "separate_encoders", False))
        self.separate_encoders = bool(getattr(args, "separate_encoders", False))
        if self.separate_encoders:
            self.encoder_mean = PFLEncoder(args)
        ctx_dim = args.social_context_size + args.dynamics_encoding_size
        self.base_ctx_dim = ctx_dim
        self.intent_condition = bool(getattr(args, "intent_condition", False))
        if self.intent_condition:
            ctx_dim += args.num_lat_classes + args.num_lon_classes
        self.ctx_dim = ctx_dim
        self.temporal_relational = bool(getattr(args, "temporal_relational", False))
        self.relation_cross_attention = bool(getattr(args, "relation_cross_attention", False))
        self.mode_conditioned = bool(getattr(args, "mode_conditioned", False))
        if self.relation_cross_attention and not self.temporal_relational:
            raise ValueError("relation_cross_attention requires temporal_relational")
        self.vf = VectorField(ctx_dim=ctx_dim, cond_dim=getattr(args, "cond_dim", 128),
                              channels=list(getattr(args, "vf_channels", None) or [64, 128, 256]),
                              dropout=float(getattr(args, "vf_dropout", 0.0)),
                              relation_dim=5 if self.temporal_relational else 0,
                              relation_cross_attention=self.relation_cross_attention,
                              relation_heads=int(getattr(args, "relation_attention_heads", 4)),
                              mode_dim=(args.num_lat_classes + args.num_lon_classes)
                                       if self.mode_conditioned else 0,
                              max_length=args.out_length)

        # Auxiliary maneuver heads. EPN trains its encoder with a maneuver cross
        # entropy alongside the trajectory loss; with the flow-matching loss alone
        # the encoder gets a far weaker and higher-variance gradient. The heads are
        # read off the context only -- the flow is never told the maneuver, so B0/B1
        # still see exactly the same information as EPN does.
        self.op_lat = nn.Linear(ctx_dim, args.num_lat_classes)
        self.op_lon = nn.Linear(ctx_dim, args.num_lon_classes)

        # Deterministic mean head. RMSE of the mean of K samples carries an irreducible
        # sigma_model^2 / K term that grows as the flow fits the true conditional spread
        # more faithfully, so a well-fitted generative decoder is penalised by exactly the
        # metric it is being judged on. This head predicts E[Y|c] directly, has no sampling
        # variance, and serves the regression columns while the flow serves the
        # distributional ones -- the same split a Gaussian-head baseline gets for free.
        if self.use_mean_head:
            h = int(getattr(args, "mean_hidden", 256))
            self.mean_head = nn.Sequential(
                nn.Linear(ctx_dim, h), nn.GELU(),
                nn.Linear(h, h), nn.GELU(),
                nn.Linear(h, args.out_length * 2),
            )

        # Residual normalisation, fitted once on the training set. Registered as
        # buffers so they travel in the state dict and evaluation reproduces exactly
        # what training used.
        self.register_buffer("res_mean", torch.zeros(args.out_length, 2))
        self.register_buffer("res_std", torch.ones(args.out_length, 2))
        self.register_buffer("stats_ready", torch.zeros((), dtype=torch.bool))

        # Per-horizon-step loss weight. x1 is standardised per step and per axis, so the
        # unweighted loss treats a 5 s error and a 1 s error as equally important while
        # RMSE, measured in feet, is dominated by the far horizon. These weights buy that
        # back; they are normalised to mean 1 so the loss scale, and with it the effective
        # learning rate, does not move when the mode changes.
        self.loss_mode = str(getattr(args, "loss_time_weight", "none"))
        self.recon_weight = float(getattr(args, "recon_weight", 0.0))
        # Not persistent: it is derived from loss_mode and res_std, and keeping it out of
        # the state dict means checkpoints stay loadable across runs that used different
        # weightings (and that checkpoints written before it existed still load).
        self.register_buffer("loss_w", torch.ones(args.out_length, 2), persistent=False)
        self._set_loss_w()

    def encode(self, *enc_args):
        return self.encoder(*enc_args)

    @staticmethod
    def _split_condition(condition):
        return condition if isinstance(condition, tuple) else (condition, None)

    def initial_state(self, sd):
        """Explicit warm-start migration: preserve old outputs with zero new columns."""
        sd = strip_derived(sd).copy()
        if not self.intent_condition:
            return sd
        current = self.state_dict()
        for key in ("vf.ce.c_proj.weight", "vf.net.ctx2ch.weight", "mean_head.0.weight",
                    "op_lat.weight", "op_lon.weight"):
            if key in current and key in sd and sd[key].shape != current[key].shape:
                if sd[key].shape != (current[key].shape[0], self.base_ctx_dim):
                    raise ValueError("Unexpected checkpoint shape for " + key)
                padded = torch.zeros_like(current[key])
                padded[:, :self.base_ctx_dim] = sd[key]
                sd[key] = padded
        # Seed the new observed-history heads from the pretrained maneuver task.
        for name in ("lat", "lon"):
            for part in ("weight", "bias"):
                key = "encoder.intent_" + name + "." + part
                source = "op_" + name + "." + part
                if key not in sd and source in sd:
                    value = sd[source]
                    sd[key] = value[:, :self.base_ctx_dim].clone() if part == "weight" else value.clone()
        return sd

    def encode_mean(self, *enc_args):
        """Context for the regression path. Falls back to the shared encoder when the
        model was built without --separate_encoders, so callers need no branch."""
        return (self.encoder_mean if self.separate_encoders else self.encoder)(*enc_args)

    @torch.no_grad()
    def _set_loss_w(self):
        if self.loss_mode == "linear":
            w = torch.arange(1, self.out_length + 1, dtype=torch.float32)
            w = w.unsqueeze(1).expand(-1, 2).contiguous()
        elif self.loss_mode == "std":
            # Undo the standardisation, so the loss is squared error in feet. This makes
            # the objective match RMSE, at the cost of handing the longitudinal axis
            # roughly 40x the lateral gradient again -- the very thing the per-axis
            # normalisation exists to prevent.
            w = self.res_std.detach().float() ** 2
        else:
            w = torch.ones(self.out_length, 2)
        self.loss_w.copy_(w / w.mean())

    # ------------------------------------------------------------------ scaling
    def cv_baseline(self, hist):
        return cv_baseline(hist, self.out_length, self.encoder.cv_gate)

    def normalize(self, fut, hist):
        """[T, B, 2] future in feet -> [B, T, 2] standardised residual."""
        y = fut.permute(1, 0, 2)
        return (y - self.cv_baseline(hist) - self.res_mean) / self.res_std

    def denormalize(self, x, hist):
        """[B, T, 2] standardised residual -> [B, T, 2] absolute future in feet."""
        return x * self.res_std + self.res_mean + self.cv_baseline(hist)

    @torch.no_grad()
    def fit_norm_stats(self, residual_sum, residual_sqsum, counts, min_std=0.05):
        """Install per-step, per-axis statistics accumulated by the caller."""
        n = counts.clamp(min=1.0)
        mean = residual_sum / n
        var = (residual_sqsum / n - mean ** 2).clamp(min=0.0)
        self.res_mean.copy_(mean)
        self.res_std.copy_(var.sqrt().clamp(min=min_std))
        self.stats_ready.fill_(True)
        self._set_loss_w()          # the "std" mode depends on the statistics just fitted

    # ------------------------------------------------------------------- losses
    def flow_loss(self, ctx, fut, mask, hist, lat_enc=None, lon_enc=None):
        ctx, relation = self._split_condition(ctx)
        x1 = self.normalize(fut, hist)
        m = mask.permute(1, 0, 2) * self.loss_w
        x0 = torch.randn_like(x1)
        t = torch.rand(x1.shape[0], device=x1.device)
        t_ = t.view(-1, 1, 1)
        xt = (1.0 - t_) * x0 + t_ * x1
        target = x1 - x0
        mode = None
        if self.mode_conditioned:
            if lat_enc is None or lon_enc is None:
                raise ValueError("maneuver labels are required for mode-conditioned training")
            mode = torch.cat([lat_enc.float(), lon_enc.float()], dim=-1)
        pred = self.vf(xt, t, ctx, relation, mode)
        err = (pred - target) ** 2
        if self.recon_weight:
            # One-step endpoint estimate. With the true velocity x1_hat is exactly x1, so
            # this term equals (1-t)^2 times the residual above: it does not add an
            # independent signal, it tilts the t weighting towards the noise end.
            x1_hat = xt + (1.0 - t_) * pred
            err = err + self.recon_weight * (x1_hat - x1) ** 2
        return (err * m).sum() / m.sum().clamp(min=1.0)

    def mean_predict(self, ctx, hist):
        """-> [B, out_length, 2] in feet. The head works in the normalised residual space
        the flow uses, so both paths share one parameterisation and one de-normalisation."""
        if not self.use_mean_head:
            raise RuntimeError("mean head is disabled for this PFL instance")
        ctx, _ = self._split_condition(ctx)
        x = self.mean_head(ctx).view(-1, self.out_length, 2)
        return self.denormalize(x, hist)

    def mean_loss(self, ctx, fut, mask, hist):
        """Squared error in feet, which is what RMSE / ADE / FDE actually measure.

        Computing it in feet rather than in the normalised space re-applies the
        lateral/longitudinal scale ratio, but for a head whose only job is the regression
        columns that ratio is the objective, not a pathology to correct.
        """
        pred = self.mean_predict(ctx, hist)
        y = fut.permute(1, 0, 2)
        m = mask.permute(1, 0, 2)
        return (((pred - y) ** 2) * m).sum() / m.sum().clamp(min=1.0)

    def maneuver_loss(self, ctx, lat_enc, lon_enc):
        ctx, _ = self._split_condition(ctx)
        if self.intent_condition:
            probs = ctx[:, self.base_ctx_dim:]
            nlat = self.args.num_lat_classes
            return (F.nll_loss(probs[:, :nlat].clamp_min(1e-8).log(), lat_enc.argmax(-1))
                    + F.nll_loss(probs[:, nlat:].clamp_min(1e-8).log(), lon_enc.argmax(-1)))
        lat = F.cross_entropy(self.op_lat(ctx), lat_enc.argmax(dim=-1))
        lon = F.cross_entropy(self.op_lon(ctx), lon_enc.argmax(dim=-1))
        return lat + lon

    # ----------------------------------------------------------------- sampling
    @torch.no_grad()
    def sample(self, ctx, hist, n_steps: int = 10, n_samples: int = 1, chunk: int = 20):
        """-> [n_samples, B, out_length, 2] in feet.

        The draws are integrated as one widened batch instead of one at a time.
        The vector field is the entire cost of sampling, and a serial loop leaves
        the GPU running a single small batch n_samples times over; at the eval
        setting of 20 draws x 50 steps that is 1000 sequential passes per batch.
        `chunk` bounds how many draws are widened at once so the activations of
        the 256-channel level still fit.
        """
        ctx, relation = self._split_condition(ctx)
        B = ctx.shape[0]
        device = ctx.device
        dt = 1.0 / n_steps
        xs = []
        for start in range(0, n_samples, max(1, chunk)):
            k = min(max(1, chunk), n_samples - start)
            c = ctx.repeat_interleave(k, dim=0)
            r = relation.repeat_interleave(k, dim=0) if relation is not None else None
            mode = None
            if self.mode_conditioned:
                lat_probs = F.softmax(self.op_lat(ctx), dim=-1)
                lon_probs = F.softmax(self.op_lon(ctx), dim=-1)
                lat_idx = torch.multinomial(lat_probs, k, replacement=True).reshape(-1)
                lon_idx = torch.multinomial(lon_probs, k, replacement=True).reshape(-1)
                mode = torch.cat([
                    F.one_hot(lat_idx, self.args.num_lat_classes),
                    F.one_hot(lon_idx, self.args.num_lon_classes),
                ], dim=-1).to(dtype=ctx.dtype)
            x = torch.randn(B * k, self.out_length, 2, device=device)
            for i in range(n_steps):
                t = torch.full((B * k,), i * dt, device=device)
                x = x + dt * self.vf(x, t, c, r, mode)
            # repeat_interleave lays the draws out as [b0 x k, b1 x k, ...], so the
            # batch axis unfolds to [B, k] and the draw axis has to come first.
            xs.append(x.view(B, k, self.out_length, 2).permute(1, 0, 2, 3))
        return torch.cat(xs, dim=0) * self.res_std + self.res_mean + self.cv_baseline(hist)

    @staticmethod
    def mean_prediction(samples):
        """Monte-Carlo estimate of E[Y | c], the quantity EPN's mu head reports.

        A single flow sample Y^ satisfies E||Y^ - Y||^2 = 2 tr(Sigma) against
        tr(Sigma) for a conditional-mean predictor, i.e. a sqrt(2) RMSE penalty that
        no amount of training removes. Averaging K samples brings that back to
        (1 + 1/K) tr(Sigma) -- 2.5% at K=20 -- so RMSE compares like with like.
        """
        return samples.mean(dim=0)

    @staticmethod
    @torch.no_grad()
    def medoid_prediction(samples):
        """Select a real sample using sample-to-sample distances only.

        No ground-truth tensor is accepted by this API, which makes accidental
        oracle use impossible at the selection boundary.
        """
        if samples.ndim != 4:
            raise ValueError("samples must have shape [K, B, T, 2]")
        flat = samples.flatten(2)                         # [K, B, 2T]
        dist = torch.cdist(flat.permute(1, 0, 2), flat.permute(1, 0, 2))
        idx = dist.sum(-1).argmin(-1)                    # [B]
        batch = torch.arange(samples.shape[1], device=samples.device)
        return samples[idx, batch]

    @staticmethod
    @torch.no_grad()
    def endpoint_oracle(samples, gt_endpoint):
        """Select by endpoint error; the explicit GT argument marks this as oracle."""
        if gt_endpoint.shape != samples.shape[1:2] + (2,):
            raise ValueError("gt_endpoint must have shape [B, 2]")
        idx = (samples[:, :, -1] - gt_endpoint).pow(2).sum(-1).argmin(0)
        batch = torch.arange(samples.shape[1], device=samples.device)
        return samples[idx, batch]

    @torch.no_grad()
    def pick_best(self, samples, fut):
        """Oracle endpoint selection, matching EPN's best-of-n destination protocol.

        Used for minADE / minFDE only; the RMSE column comes from mean_prediction.
        """
        return self.endpoint_oracle(samples, fut[-1])

    @torch.no_grad()
    def pick_best_dest(self, samples, fut):
        """The selected sample's endpoint, i.e. EPN's `best_guess_dest`."""
        dest = fut[-1]
        err = (samples[:, :, -1, :] - dest).pow(2).sum(-1)
        idx = err.argmin(0)
        b = torch.arange(samples.shape[1], device=samples.device)
        return samples[idx, b, -1, :]

    @staticmethod
    @torch.no_grad()
    def cond_mean(samples, dest, beta, gamma=0.0):
        """Estimate E[Y | c, Y(T) ~= dest] by kernel-weighting draws on their endpoint.

        Under oracle selection EPN returns the conditional *mean* given the chosen
        destination, because its decoder is deterministic once the destination is
        fixed. Picking one flow draw returns a conditional *sample* instead, which
        carries E||Y^ - Y||^2 = 2 tr(Sigma_|d) against tr(Sigma_|d) -- the same
        sqrt(2) penalty mean_prediction removes for the unconditional column, but
        applied to the endpoint-conditioned law. Weighting the draws by

            w_i  ~  exp(-||Y_i(T) - dest||^2 / (2 h^2)),  h = beta * spread(Y(T))

        recovers that mean without a conditional sampler: beta -> 0 falls back to
        the single best draw, beta -> inf to the unconditional mean.

        The bandwidth may vary along the trajectory. Since the regression slope of
        Y(t) on Y(T) is Cov(Y(t), Y(T)) / Var(Y(T)) ~ t/T, blurring the endpoint by h
        propagates only (t/T) h of bias to time t, so the tolerable bandwidth grows
        as T/t towards the start. gamma=0 keeps the single global bandwidth.
        """
        K, B, T, _ = samples.shape
        end = samples[:, :, -1, :]
        d2 = (end - dest.unsqueeze(0)).pow(2).sum(-1)                     # [K, B]
        spread = end.std(dim=0).pow(2).sum(-1).sqrt().clamp_min(1e-6)     # [B]
        steps = torch.arange(1, T + 1, device=samples.device, dtype=samples.dtype)
        scale = (T / steps).pow(gamma)                                    # [T]
        h2 = (beta * spread[:, None] * scale[None, :]).pow(2)             # [B, T]
        w = torch.softmax(-d2[:, :, None] / (2.0 * h2)[None], dim=0)      # [K, B, T]
        return (w.unsqueeze(-1) * samples).sum(0)
